"""SQLAlchemy models for every table. Columns are snake_case; JSON payloads map to camelCase in schemas/.

Conventions: uuid ids generated by Postgres, timestamptz timestamps, integer PKR money.
Names are never unique; only ids, inventory_items.sku and inspirations.slug are.
"""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    SmallInteger,
    Table,
    Text,
    Uuid,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app import constants as c

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


# Reference-only stub so profiles.id can point at Supabase's auth.users.
# Alembic is configured to ignore the `auth` schema; this table is never created by us.
auth_users = Table("users", Base.metadata, Column("id", Uuid, primary_key=True), schema="auth")


def _in(column: str, values: tuple[str, ...]) -> str:
    quoted = ", ".join("'" + v.replace("'", "''") + "'" for v in values)
    return f"{column} in ({quoted})"


def _id() -> Mapped[uuid.UUID]:
    return mapped_column(Uuid, primary_key=True, server_default=text("gen_random_uuid()"))


def _created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


def _updated_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())


def _text_array() -> Mapped[list[str]]:
    return mapped_column(ARRAY(Text), nullable=False, server_default=text("'{}'::text[]"))


def _profile_fk(nullable: bool = True, ondelete: str = "SET NULL") -> Mapped[uuid.UUID | None]:
    return mapped_column(ForeignKey("profiles.id", ondelete=ondelete), nullable=nullable)


class Profile(Base):
    """One row per Supabase auth user. Admins act as consultants."""

    __tablename__ = "profiles"
    __table_args__ = (
        CheckConstraint(_in("role", c.ROLES), name="role"),
        CheckConstraint(_in("access_status", c.ACCESS_STATUSES), name="access_status"),
        CheckConstraint(_in("invitation_status", c.INVITATION_STATUSES), name="invitation_status"),
        CheckConstraint("client_role is null or " + _in("client_role", c.CLIENT_ROLES), name="client_role"),
        CheckConstraint("role <> 'client' or access_expires_at is not null", name="client_has_expiry"),
        CheckConstraint("not is_superuser or role = 'admin'", name="superuser_is_admin"),
    )

    id: Mapped[uuid.UUID] = mapped_column(ForeignKey("auth.users.id", ondelete="CASCADE"), primary_key=True)
    role: Mapped[str] = mapped_column(Text, nullable=False)
    is_superuser: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    full_name: Mapped[str] = mapped_column(Text, nullable=False)
    email: Mapped[str] = mapped_column(Text, nullable=False)
    phone: Mapped[str | None] = mapped_column(Text)
    city: Mapped[str | None] = mapped_column(Text)
    client_role: Mapped[str | None] = mapped_column(Text)
    partner_name: Mapped[str | None] = mapped_column(Text)
    emergency_contact_name: Mapped[str | None] = mapped_column(Text)
    emergency_contact_phone: Mapped[str | None] = mapped_column(Text)
    access_expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    access_status: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'active'"))
    invitation_status: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'pending'"))
    invited_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    invited_by: Mapped[uuid.UUID | None] = _profile_fk()
    activated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    assigned_admin_id: Mapped[uuid.UUID | None] = _profile_fk()
    notification_prefs: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False, server_default=text("'{}'::jsonb"))
    consent: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = _updated_at()


